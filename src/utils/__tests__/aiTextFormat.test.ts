import { v_dff48a } from '../aiTextFormat';

describe('stripLatexMarkup', () => {
  it('인라인 수식 델리미터를 벗기고 이스케이프한 퍼센트를 복원한다', () => {
    expect(v_dff48a('공복혈당 위험도는 $3\\%$로 주의가 필요합니다.')).toBe(
      '공복혈당 위험도는 3%로 주의가 필요합니다.',
    );
  });

  it('델리미터 없이 이스케이프된 퍼센트도 복원한다', () => {
    expect(v_dff48a('심혈관 위험도 5\\% 수준입니다.')).toBe('심혈관 위험도 5% 수준입니다.');
  });

  it('백슬래시 없는 수식도 델리미터를 벗긴다 (실측: 건강지수·혈압)', () => {
    expect(v_dff48a('건강 지수인 $7/10$과 건강 수준이 좋음으로 측정되었습니다.')).toBe(
      '건강 지수인 7/10과 건강 수준이 좋음으로 측정되었습니다.',
    );
    expect(v_dff48a('혈압 또한 $129/81$ mmHg로 정상적인 수치를 보입니다.')).toBe(
      '혈압 또한 129/81 mmHg로 정상적인 수치를 보입니다.',
    );
  });

  it('통화 표기의 달러 기호는 수식으로 오인하지 않는다', () => {
    expect(v_dff48a('가격은 $100 이고 배송비는 $5 입니다')).toBe(
      '가격은 $100 이고 배송비는 $5 입니다',
    );
  });
});
